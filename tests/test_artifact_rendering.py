"""Artifact-QA Mode 3 — 17 artefact x 10 profile = 170 case render matrix.

Spec source: ``.claude/agents/artifact-qa.md`` Mode 3.

Selection
---------
The 17 artefact slugs below are the canonical render set; ``monthly_brag``
is intentionally excluded because it is a legacy duplicate of
``brag_card`` (both map to the same template family but only ``brag_card``
is wired into the unified ``/api/artifacts/generate`` dispatch table).

Workflow per case
-----------------
1. Seed the 10-profile fixture into the isolated SQLite DB.
2. Resolve the artefact service class.
3. Call ``service.generate_for_user(user_id)`` to produce the
   structured payload (or pull from ``services.artifacts.sample_data``
   when the service's generator is unsuitable for synthetic users).
4. Call ``service.render_html(data)`` — must succeed and exceed a
   minimum byte threshold.
5. Call ``service.render_pdf(data)`` when WeasyPrint is installed;
   otherwise the PDF branch is conditionally skipped (the HTML branch
   still asserts).  Generated bytes are written to
   ``tests/artifacts/output/{user_id}/{slug}.pdf``.
6. Optional ``pypdf`` extraction confirms ≥1 page and ≥100 bytes of
   recoverable text.
7. ``_disclaimer.html`` include is assert-checked on every rendered
   HTML (자본시장법 §101 면제 4요건 cross-ref).

Marker
------
All tests carry ``@pytest.mark.artifact_qa`` so the matrix is opt-in:
``pytest -m artifact_qa tests/test_artifact_rendering.py``.

Empty / high-load edge cases
----------------------------
Profile 8 (``new_signup``, portfolio_size=0) and profile 5
(``hyper_diversified``, portfolio_size=75 + 200 trades) are inherently
exercised by the matrix — the per-test assertions branch on
``profile.flags`` to accept empty-state fallbacks (``status='empty'``)
without failing the case.
"""
